import { Sparkles } from 'lucide-react';
import type { SourceRef } from '../lib/api';
import { cn } from '../lib/format';

/**
 * Transparency rule: anything produced by an AI agent carries this badge
 * (with the model name) until a human approves it.
 */
export function AiBadge({ model, className }: { model?: string | null; className?: string }) {
  return (
    <span
      title={model ? `Generated by ${model}. Not yet approved by a human.` : 'Generated by an AI agent. Not yet approved by a human.'}
      className={cn(
        'inline-flex max-w-full items-center gap-1 rounded-md border border-dashed border-amber-400 bg-amber-50 px-1.5 py-0.5 text-[11px] font-medium leading-4 text-amber-800',
        'dark:border-amber-500/60 dark:bg-amber-500/10 dark:text-amber-300',
        className,
      )}
    >
      <Sparkles className="h-3 w-3 shrink-0" aria-hidden />
      <span className="whitespace-nowrap">AI-generated</span>
      {model && <span className="truncate font-mono font-normal opacity-80">· {model}</span>}
    </span>
  );
}

function locator(s: SourceRef): string {
  const parts: string[] = [];
  if (s.page != null) parts.push(`p. ${s.page}`);
  if (s.section) parts.push(s.section);
  return parts.join(' · ');
}

/** The sources an AI output was derived from: filename, page / section, quote. */
export function SourceList({ sources, emptyText = 'No sources were recorded.' }: { sources: SourceRef[] | null | undefined; emptyText?: string }) {
  if (!sources || sources.length === 0) return <p className="text-xs text-muted">{emptyText}</p>;
  return (
    <ul className="space-y-2">
      {sources.map((s, i) => (
        <li key={i} className="rounded-md border border-line bg-bg px-3 py-2">
          <div className="flex flex-wrap items-baseline gap-x-2 text-xs">
            <span className="break-all font-medium text-fg">{s.filename ?? s.document_id ?? 'Source'}</span>
            {locator(s) && <span className="text-muted">{locator(s)}</span>}
          </div>
          {s.quote && (
            <blockquote className="mt-1.5 border-l-2 border-line-strong text-xs italic leading-relaxed text-muted" style={{ paddingLeft: 10 }}>
              “{s.quote}”
            </blockquote>
          )}
        </li>
      ))}
    </ul>
  );
}
